"""Idempotent private community tables; no Data API grants or data cleanup."""
from __future__ import annotations


STATUSES = {
    "bug": ("open", "in_progress", "fixed", "closed"),
    "suggestion": ("open", "accepted", "in_progress", "done", "rejected"),
    "roadmap": ("planned", "in_progress", "done"),
    "showcase": ("published",),
    "release": ("published",),
    "deploy": ("pending", "building", "starting", "live", "failed", "canceled", "unconfirmed"),
}
DEFAULT_STATUS = {kind: statuses[0] for kind, statuses in STATUSES.items()}
STATUS_CASE_SQL = "CASE kind " + " ".join(
    f"WHEN '{kind}' THEN ARRAY[{','.join(repr(status) for status in statuses)}]::text[]"
    for kind, statuses in STATUSES.items()
) + " ELSE ARRAY[]::text[] END"

SQL = (
    "CREATE SCHEMA IF NOT EXISTS esil_internal",
    "REVOKE ALL ON SCHEMA esil_internal FROM PUBLIC",
    f"""CREATE TABLE IF NOT EXISTS esil_internal.community_items (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        guild_id BIGINT NOT NULL CHECK (guild_id > 0),
        kind TEXT NOT NULL CHECK (kind IN ('bug','suggestion','roadmap','showcase','release','deploy')),
        author_id BIGINT NOT NULL CHECK (author_id > 0),
        title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
        body TEXT NOT NULL DEFAULT '' CHECK (char_length(body) <= 6000),
        status TEXT NOT NULL CHECK (status = ANY ({STATUS_CASE_SQL})),
        details JSONB NOT NULL DEFAULT '{{}}'::jsonb CHECK (jsonb_typeof(details) = 'object'),
        seed_key TEXT CHECK (seed_key IS NULL OR char_length(seed_key) BETWEEN 1 AND 160),
        channel_id BIGINT CHECK (channel_id > 0),
        message_id BIGINT CHECK (message_id > 0),
        created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_by BIGINT NOT NULL CHECK (updated_by > 0),
        UNIQUE (guild_id, id),
        UNIQUE (guild_id, kind, seed_key)
    )""",
    """CREATE INDEX IF NOT EXISTS community_items_guild_kind_created
       ON esil_internal.community_items (guild_id, kind, created_at DESC, id DESC)""",
    """CREATE INDEX IF NOT EXISTS community_items_guild_kind_status
       ON esil_internal.community_items (guild_id, kind, status, updated_at DESC, id DESC)""",
    """CREATE TABLE IF NOT EXISTS esil_internal.community_votes (
        guild_id BIGINT NOT NULL,
        item_id BIGINT NOT NULL,
        user_id BIGINT NOT NULL CHECK (user_id > 0),
        value SMALLINT NOT NULL CHECK (value IN (-1,0,1)),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        PRIMARY KEY (guild_id, item_id, user_id),
        FOREIGN KEY (guild_id, item_id)
            REFERENCES esil_internal.community_items (guild_id, id) ON DELETE CASCADE
    )""",
    """CREATE TABLE IF NOT EXISTS esil_internal.community_settings (
        guild_id BIGINT NOT NULL CHECK (guild_id > 0),
        key TEXT NOT NULL CHECK (char_length(key) BETWEEN 1 AND 80),
        value JSONB NOT NULL CHECK (jsonb_typeof(value) = 'object'),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
        PRIMARY KEY (guild_id, key)
    )""",
    *(f"ALTER TABLE esil_internal.{table} ENABLE ROW LEVEL SECURITY" for table in (
        "community_items", "community_votes", "community_settings",
    )),
    *(f"REVOKE ALL ON esil_internal.{table} FROM PUBLIC" for table in (
        "community_items", "community_votes", "community_settings",
    )),
    "REVOKE ALL ON SEQUENCE esil_internal.community_items_id_seq FROM PUBLIC",
    """DO $vivian_community$ DECLARE api_role TEXT; table_name TEXT; BEGIN
        FOREACH api_role IN ARRAY ARRAY['anon','authenticated'] LOOP
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
                EXECUTE format('REVOKE ALL ON SCHEMA esil_internal FROM %I', api_role);
                FOREACH table_name IN ARRAY ARRAY[
                    'community_items','community_votes','community_settings'
                ] LOOP
                    EXECUTE format('REVOKE ALL ON esil_internal.%I FROM %I', table_name, api_role);
                END LOOP;
                EXECUTE format('REVOKE ALL ON SEQUENCE esil_internal.community_items_id_seq FROM %I', api_role);
            END IF;
        END LOOP;
    END $vivian_community$""",
)
