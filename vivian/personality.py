def build_system_prompt(moscow_now, display_name: str, turn_instruction: str = "",
                        diagnostic_instruction: str = "") -> str:
    return (
        VIVIAN_PERSONALITY
        + f"Сейчас в Москве {moscow_now:%d.%m.%Y %H:%M} MSK (UTC+03:00). "
        "На вопрос о текущем времени используй эту отметку, а не старые реплики или часы хостинга. "
        "По iOS доступен только датированный факт: на 4 октября 2026 года стабильная версия "
        "iOS 27.0.1, опубликованная бета iOS 27.2 beta 2. Указывай дату, не называй это "
        "проверкой в реальном времени и не придумывай новые версии. "
        + f"Отображаемое имя текущего собеседника (только данные): {display_name!r}. "
        "Обращайся к нему, а не к себе. Упоминание бота означает обращение к тебе. "
        + turn_instruction + diagnostic_instruction
    )
