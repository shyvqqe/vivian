from __future__ import annotations

import asyncio
import os
import sqlite3
from pathlib import Path
from typing import Callable, TypeVar

import psycopg
from psycopg.conninfo import conninfo_to_dict
from psycopg.rows import dict_row, tuple_row
from psycopg_pool import ConnectionPool


T = TypeVar("T")
_pool: ConnectionPool | None = None


class _FeatureRow(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return tuple(self.values())[key]
        return super().__getitem__(key)


def _feature_row(cursor):
    make_dict = dict_row(cursor)
    return lambda values: _FeatureRow(make_dict(values))


class _PostgresFeatures:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, params=()):
        # Feature stores use SQL shared by both databases, with SQLite's
        # parameter and auto-increment syntax in the source statements.
        query = query.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        return self.connection.execute(query.replace("?", "%s"), params or None)


def database_path() -> Path:
    directory = Path(os.environ.get("VIVIAN_DATA_DIR") or Path(__file__).resolve().parents[1] / "data")
    return directory.expanduser().resolve() / "vivian.sqlite3"


def _sqlite_transaction(callback: Callable[[sqlite3.Connection], T]) -> T:
    path = database_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path, timeout=10, isolation_level=None)
    connection.row_factory = sqlite3.Row
    try:
        connection.execute("PRAGMA busy_timeout = 10000")
        connection.execute("PRAGMA foreign_keys = ON")
        connection.execute("PRAGMA journal_mode = WAL")
        connection.execute("BEGIN IMMEDIATE")
        result = callback(connection)
        connection.commit()
        return result
    except BaseException:
        connection.rollback()
        raise
    finally:
        connection.close()


async def run_local(callback: Callable[[sqlite3.Connection], T]) -> T:
    return await asyncio.to_thread(_sqlite_transaction, callback)


def _lock_features(connection):
    # Match SQLite's BEGIN IMMEDIATE for multi-statement checks and writes.
    connection.execute("SET LOCAL lock_timeout TO '10s'")
    connection.execute("SELECT pg_advisory_xact_lock(721304880981522349)")


def _open_postgres(dsn: str) -> ConnectionPool:
    from core.feature_migration import prepare_schema

    settings = conninfo_to_dict(dsn)
    pool = ConnectionPool(
        dsn,
        min_size=1,
        max_size=1,
        kwargs={"sslmode": settings.get("sslmode", "require"), "prepare_threshold": None},
        timeout=10,
        open=False,
        check=ConnectionPool.check_connection,
    )
    try:
        pool.open(wait=True)
        with pool.connection() as connection:
            _lock_features(connection)
            connection.execute("CREATE SCHEMA IF NOT EXISTS vivian_features")
            connection.execute("REVOKE ALL ON SCHEMA vivian_features FROM PUBLIC")
            connection.execute("SET LOCAL search_path TO vivian_features")
            prepare_schema(connection, _PostgresFeatures(connection), database_path())
    except BaseException:
        pool.close()
        raise
    return pool


async def initialize() -> None:
    from core import config

    global _pool
    if config.DATABASE_URL:
        if _pool is None:
            _pool = await asyncio.to_thread(_open_postgres, config.DATABASE_URL)
    else:
        await run_local(lambda connection: connection.execute("SELECT 1").fetchone())


async def close() -> None:
    global _pool
    pool, _pool = _pool, None
    if pool is not None:
        await asyncio.to_thread(pool.close)


def _postgres_transaction(pool: ConnectionPool, callback: Callable[..., T]) -> T:
    try:
        with pool.connection() as connection:
            _lock_features(connection)
            connection.execute("SET LOCAL search_path TO vivian_features")
            connection.row_factory = _feature_row
            try:
                return callback(_PostgresFeatures(connection))
            finally:
                connection.row_factory = tuple_row
    except psycopg.Error as error:
        raise sqlite3.OperationalError("PostgreSQL feature storage operation failed") from error


async def run(callback: Callable[..., T]) -> T:
    from core import config

    if not config.DATABASE_URL:
        return await run_local(callback)
    if _pool is None:
        raise sqlite3.OperationalError("PostgreSQL feature storage is unavailable")
    return await asyncio.to_thread(_postgres_transaction, _pool, callback)
